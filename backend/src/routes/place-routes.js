const router = require('express').Router();
const { asyncHandler } = require('../utils/async-handler');
const { auth } = require('../middleware/auth');
const { simulateError } = require('../middleware/simulate-error');
const c = require('../controllers/place-controller');
router.use(auth, simulateError);
router.get('/search', asyncHandler(c.searchPlaces));
router.get('/recommendations', asyncHandler(c.recommendations));
router.get('/', asyncHandler(c.listPlaces));
router.get('/:id', asyncHandler(c.getPlace));
module.exports = router;
